// Disposable local-container QA. No production credentials are stored.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { execFileSync } = require('node:child_process');
const { randomBytes } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.HYPANEL_TEST_URL || 'http://localhost:18095';

(async () => {
  fs.mkdirSync('artifacts', {recursive:true});
  const password = randomBytes(24).toString('base64url');
  const key = execFileSync('docker',['exec','hypanel-smoke','cat','/data/setup.key'],{encoding:'utf8'}).trim();
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.getByLabel('Einrichtungsschlüssel').fill(key);
  await page.getByLabel('Benutzername',{exact:true}).fill('qa-admin');
  await page.getByLabel('Passwort',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Administratorkonto erstellen'}).click();
  await page.getByRole('button',{name:'Server erstellen',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('QA Hytale');
  await page.getByLabel('UDP-Port').fill('15520');
  await page.getByRole('button',{name:'Erstellen',exact:true}).click();
  await page.getByRole('button',{name:'Öffnen',exact:true}).click();
  await page.getByRole('button',{name:'Dateien',exact:true}).click();
  await page.getByRole('button',{name:'Datei erstellen'}).click();
  await page.getByLabel('Dateiname').fill('test.json');
  await page.getByRole('button',{name:'Speichern',exact:true}).click();
  await page.getByLabel('Dateiinhalt').fill('{"qa":"passed"}');
  await page.getByRole('button',{name:'Speichern',exact:true}).click();
  await page.getByRole('button',{name:'Zurück',exact:true}).click();
  await page.getByRole('button',{name:'test.json',exact:true}).waitFor();
  await page.getByRole('button',{name:'Backups',exact:true}).click();
  await page.getByRole('button',{name:'Daten sichern',exact:true}).click();
  await page.getByRole('button',{name:'Wiederherstellen',exact:true}).waitFor();
  await page.getByRole('button',{name:'Zeitpläne',exact:true}).click();
  await page.getByRole('button',{name:'Zeitplan erstellen',exact:true}).click();
  await page.getByRole('button',{name:'Speichern',exact:true}).click();
  await page.getByRole('cell',{name:'Tägliches Backup',exact:true}).waitFor();
  await page.getByRole('button',{name:'Einstellungen',exact:true}).click();
  await page.getByRole('heading',{name:'Ressourcen und Start'}).waitFor();
  await page.screenshot({path:'artifacts/server-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Mein Konto',exact:true}).click();
  await page.getByRole('button',{name:'Schlüssel erstellen',exact:true}).click();
  await page.getByLabel('Name',{exact:true}).fill('Browser QA');
  await page.getByRole('button',{name:'Speichern',exact:true}).click();
  await page.getByRole('heading',{name:'API-Schlüssel erstellt',exact:true}).waitFor();
  assert.match(await page.locator('#token-value').inputValue(),/^hyp_/);
  await page.getByRole('button',{name:'Schließen',exact:true}).click();
  await page.getByRole('button',{name:'Widerrufen',exact:true}).click();
  await page.locator('dialog').getByRole('button',{name:'Widerrufen',exact:true}).click();
  await page.getByText('Keine API-Schlüssel.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Server',exact:true}).click();
  await page.screenshot({path:'artifacts/servers-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/servers-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true,'mobile overflow');
  await page.getByRole('button',{name:'Abmelden',exact:true}).click();
  await page.getByRole('heading',{name:'Anmelden',exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser QA passed: onboarding, server create, file editor, backup, schedule, API key create/revoke, logout, desktop/mobile.');
})().catch(e=>{console.error(e.message);process.exit(1);});
